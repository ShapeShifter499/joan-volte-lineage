#!/usr/bin/env python3
"""Generate the AOSP IMS zip's installer and uninstaller from joan's.

joan's scripts/update-binary (installer v8) is the one that flashes cleanly
across LineageOS-based ROMs: it mounts dynamic partitions the way alpha67
did, writes every file atomically, checks free space before touching
anything, orders the privapp allowlist before the apk, and stamps the
package cache so PackageManager rereads what changed (the fix for the
post-alpha67 bootloop). Rather than fork that logic, this rewrites the
names of what it installs and adds what the AOSP stack needs: the
sysconfig file, hints naming this stack's own launcher entry, and one
of two joan policies. update-binary (fresh flash) refuses a phone that has
joan, before writing anything; update-binary-migrate removes joan's stack,
which this one replaces, keeping the files both share.

Every rewrite must match the expected number of times, so a change to the
joan scripts fails this build instead of producing a half-renamed
installer.

Usage: make-installer.py <scripts dir> <out dir>
"""
