def rewrite(src, rules, name):
    text = open(src).read()
    for old, new, count in rules:
        n = text.count(old)
        if n != count:
            raise SystemExit(f'{name}: expected {count}x {old[:60]!r}, found {n}')
        text = text.replace(old, new)
    # joan names that must not survive, outside the migration block and
    # the leftover cleanups that stay deliberately.
    allowed = ('priv-app/JoanIms"', 'JoanImsPhoneDefault.apk', 'JoanFwVolte.apk',
               'org.joan.ims.xml', 'joan-ims-ua', 'joan-ims.rc', 'joan-imsd.rc',
               'bin/joan-ims"', 'joan-grant', 'joan-orig', 'joan-added',
               'joan-merged', 'joan-new', 'joan-viettel', '/mnt/joan_')
    for line in text.splitlines():
        if line.lstrip().startswith('#'):
            continue
        stripped = line
        for a in allowed:
            stripped = stripped.replace(a, '')
        if 'JoanIms' in stripped or 'org.joan.ims' in stripped:
            raise SystemExit(f'{name}: joan name left in: {line.strip()}')
    head, rest = text.split('\n', 1)
    return head + '\n' + BANNER.format(src=name) + rest


def main(scripts, out):
    os.makedirs(out, exist_ok=True)
    for src, rules, dst in (('update-binary', INSTALL + FRESH, 'update-binary'),
                            ('update-binary', INSTALL + MIGRATE, 'update-binary-migrate'),
                            ('update-binary-cleanup', UNINSTALL, 'update-binary-cleanup')):
        text = rewrite(os.path.join(scripts, src), rules, src)
        path = os.path.join(out, dst)
        with open(path, 'w') as f:
            f.write(text)
        os.chmod(path, 0o755)
        print(f'wrote {path}')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
